import { createRequire } from "node:module";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { mock } from "node:test";

mock.timers.enable({ apis: ["Date"], now: new Date("2026-10-25T07:00:00.000Z") });
const root = process.cwd();
const requireLegacy = createRequire(resolve(root, "package.json"));
const load = (path) => import(pathToFileURL(resolve(root, path)).href);
const { createAnalyticsState } = await load("../apiNest/tests/fixtures/analyticsState.ts");
const state = await createAnalyticsState();
state.user.role = "ADMIN";
globalThis.prisma = state.prisma;
const { amalyticsRoutes } = await load("src/routes/admin/amalyticsRoutes.ts");
const { adminDashboardRoutes } = await load("src/routes/admin/adminDashboardRoutes.ts");
const { errorHandlerMiddleware } = await load("src/middlewares/errorHandlerMiddleware.ts");
const express = requireLegacy("express");
const app = express();
app.use(express.json({ verify: (request, _response, buffer) => { request.rawBody = buffer.toString("utf8"); } }));
app.use(express.urlencoded({ extended: true }));
app.use("/api/v1/admin/amalytics", amalyticsRoutes);
app.use("/api/v1/admin/dashboard", adminDashboardRoutes);
app.use(errorHandlerMiddleware);
const server = app.listen(0, "127.0.0.1", () => process.send({ port: server.address().port }));
process.on("message", (message) => { if (message === "close") server.close(() => process.exit(0)); });
process.on("disconnect", () => server.close());
