import "../harness/testEnvironment.js";
import assert from "node:assert/strict";
import { test } from "node:test";
import { TokenService } from "@/modules/auth/security/token.service.js";
import { AdminBlogService } from "@/modules/blogs/services/adminBlog.service.js";
import { createAdminBlogPostDto } from "@/modules/blogs/dto/adminBlog.dto.js";
import { authRequest, startAuthApplication } from "../harness/authApplication.js";
import { createBlogState } from "../fixtures/blogState.js";

test("blog administration preserves permissions, fallback tag/author, publishing, thumbnails and cache invalidation", async (context) => {
  context.mock.timers.enable({ apis: ["Date"], now: new Date("2026-10-24T14:00:00.000Z") });
  const state = await createBlogState();
  const server = await startAuthApplication(async () => state);
  const token = server.app.get(TokenService).signAdminAccessToken({ sub: state.user.id, email: state.user.email, role: "ADMIN", tokenType: "ADMIN" });
  const request = (path: string, method = "GET", body?: unknown) => authRequest(server.url, path, body, { token, method });
  const payload = { title: "Bài mới", slug: "new-post", excerpt: "Mô tả", contentHtml: "<p>Blog</p>", tagId: "missing-tag", thumbnailUrl: "https://example.test/thumb.png", images: [{ url: "https://example.test/thumb.png" }, { url: "https://example.test/extra.png" }] };
  try {
    state.user.role = "STAFF_ORDER";
    assert.equal((await request("/admin/blog/tags")).body.errorCode, "FORBIDDEN");
    assert.equal((await request("/admin/blog/posts", "POST", payload)).body.errorCode, "FORBIDDEN");
    state.user.role = "STAFF_CONTENT";
    await request("/blog/posts?home=true&limit=4");
    const tag = await request("/admin/blog/tags", "POST", { name: "New Topic" });
    assert.equal(tag.response.status, 201);
    assert.equal(tag.body.data.slug, "new-topic");
    assert.equal(await state.redis.get("client:blog-posts:home:4"), null);
    assert.equal((await request(`/admin/blog/tags/${tag.body.data.id}`, "PATCH", { name: "Updated Topic" })).body.data.slug, "updated-topic");
    assert.deepEqual((await request(`/admin/blog/tags/${tag.body.data.id}`, "DELETE")).body, { success: true, message: "Xóa chủ đề thành công." });
    assert.equal((await request(`/admin/blog/tags/${state.activeTag.id}`, "DELETE")).response.status, 400);
    assert.equal((await request("/admin/blog/tags/missing", "DELETE")).response.status, 404);
    const tags = await request("/admin/blog/tags");
    assert.equal(tags.body.data.find((tag: { id: string }) => tag.id === state.activeTag.id)._count.posts, 5);
    const created = await request("/admin/blog/posts", "POST", payload);
    assert.equal(created.response.status, 201);
    const post = created.body.data;
    assert.equal(post.status, "DRAFT");
    assert.equal(post.tag.id, state.activeTag.id);
    assert.equal(post.author.id, state.user.id);
    assert.equal(post.publishedAt, null);
    assert.equal(post.images.length, 2);
    assert.equal(post.thumbnail.url, payload.thumbnailUrl);
    assert.equal(post.images[1].displayOrder, 1);
    context.mock.timers.setTime(new Date("2026-10-24T14:00:01.000Z").getTime());
    const duplicate = await request("/admin/blog/posts", "POST", payload);
    assert.equal(duplicate.body.data.slug, `new-post-${Date.now().toString().slice(-4)}`);
    const publish = await request(`/admin/blog/posts/${post.id}/status`, "PATCH", { status: "PUBLISHED" });
    assert.deepEqual(publish.body, { success: true, message: "Cập nhật trạng thái bài viết thành công." });
    const publishedAt = state.posts.get(post.id)!.publishedAt;
    assert.ok(publishedAt instanceof Date);
    assert.equal((await request(`/blog/posts/${post.slug}`)).response.status, 200);
    const updated = await request(`/admin/blog/posts/${post.id}`, "PATCH", { thumbnailUrl: "https://example.test/new-thumb.png", isFeatured: true, showOnHome: true, metaTitle: null, publishedAt: null });
    assert.equal(updated.body.data.thumbnail.url, "https://example.test/new-thumb.png");
    assert.equal(updated.body.data.publishedAt, null);
    assert.equal(updated.body.data.images.length, 2);
    const listing = await request("/admin/blog/posts?status=DRAFT&sort=VIEWS_DESC&page=1&limit=2");
    assert.equal(listing.body.data.pagination.totalPages, 1);
    assert.deepEqual(state.queries.at(-1)?.args.orderBy, [{ viewCount: "desc" }]);
    assert.equal((await request(`/admin/blog/posts/${post.id}`)).body.data.id, post.id);
    assert.deepEqual((await request(`/admin/blog/posts/${post.id}`, "DELETE")).body, { success: true, message: "Xóa bài viết thành công." });
    assert.ok(state.posts.get(post.id)!.deletedAt instanceof Date);
    assert.equal((await request(`/admin/blog/posts/${post.id}`)).response.status, 404);
    state.tags.clear();
    context.mock.timers.setTime(Date.now() + 1000);
    const fallback = await server.app.get(AdminBlogService).createPost(createAdminBlogPostDto.parse({ body: { ...payload, slug: "fallback" } }).body, "missing-author");
    assert.equal(fallback.tag.code, "TAG-01");
    assert.equal(fallback.author?.id, state.user.id);
  } finally { await server.close(); }
});
