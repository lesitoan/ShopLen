import { createRequire } from "node:module";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { mock } from "node:test";

mock.timers.enable({ apis: ["Date"], now: new Date("2026-10-24T14:00:00.000Z") });
const root = process.cwd();
const requireLegacy = createRequire(resolve(root, "package.json"));
const load = (path) => import(pathToFileURL(resolve(root, path)).href);
const { Prisma } = requireLegacy("@prisma/client");
const { createBlogState } = await load("../apiNest/tests/fixtures/blogState.ts");
const state = await createBlogState(Prisma.PrismaClientKnownRequestError);
state.user.role = "STAFF_CONTENT";
globalThis.prisma = state.prisma;
globalThis.redisClient = Object.assign(state.redis, { isOpen: true, on: () => {} });
const { cloudinaryService } = await load("src/services/cloudinaryService.ts");
cloudinaryService.uploadImageBuffer = async () => ({ url: "https://example.test/avatar.webp", publicId: "avatars/test" });
const { blogRoutes } = await load("src/routes/client/blogRoutes.ts");
const { adminBlogRoutes } = await load("src/routes/admin/adminBlogRoutes.ts");
const { uploadRoutes } = await load("src/routes/admin/uploadRoutes.ts");
const { errorHandlerMiddleware } = await load("src/middlewares/errorHandlerMiddleware.ts");
const express = requireLegacy("express");
const app = express();
app.use(express.json());
app.use("/api/v1/blog", blogRoutes);
app.use("/api/v1/admin/blog", adminBlogRoutes);
app.use("/api/v1/admin/upload", uploadRoutes);
app.use(errorHandlerMiddleware);
const server = app.listen(0, "127.0.0.1", () => process.send({ port: server.address().port }));
process.on("message", (message) => { if (message === "close") server.close(() => process.exit(0)); });
process.on("disconnect", () => server.close());
