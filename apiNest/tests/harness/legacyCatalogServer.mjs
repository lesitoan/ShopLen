import { createRequire } from "node:module";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = process.cwd();
const requireLegacy = createRequire(resolve(root, "package.json"));
const load = (path) => import(pathToFileURL(resolve(root, path)).href);
Date.now = () => new Date("2026-01-15T00:00:00.000Z").getTime();
const { Prisma } = requireLegacy("@prisma/client");
const { createCatalogState } = await load("../apiNest/tests/fixtures/catalogState.ts");
const state = await createCatalogState(Prisma.PrismaClientKnownRequestError);
globalThis.prisma = state.prisma;
globalThis.redisClient = Object.assign(state.redis, { isOpen: true, on: () => {} });
globalThis.notificationQueueConnection = { on: () => {} };
globalThis.notificationQueue = {};
const { categoryRoutes } = await load("src/routes/client/categoryRoutes.ts");
const { adminCategoryRoutes } = await load("src/routes/admin/adminCategoryRoutes.ts");
const { productRoutes } = await load("src/routes/client/productRoutes.ts");
const { adminProductRoutes } = await load("src/routes/admin/adminProductRoutes.ts");
const { cartRoutes } = await load("src/routes/client/cartRoutes.ts");
const { errorHandlerMiddleware } = await load("src/middlewares/errorHandlerMiddleware.ts");
const express = requireLegacy("express");
const app = express();
app.use(express.json());
app.use("/api/v1/categories", categoryRoutes);
app.use("/api/v1/admin/categories", adminCategoryRoutes);
app.use("/api/v1/products", productRoutes);
app.use("/api/v1/admin/products", adminProductRoutes);
app.use("/api/v1/cart", cartRoutes);
app.use(errorHandlerMiddleware);
const server = app.listen(0, "127.0.0.1", () => process.send({ port: server.address().port }));
process.on("message", (message) => {
  if (message === "close") server.close(() => process.exit(0));
});
process.on("disconnect", () => server.close());
